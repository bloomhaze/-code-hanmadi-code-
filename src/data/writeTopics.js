// 모든 질문을 { q, cat } 형태로 펼침. cat = 카테고리 인덱스(내부용).
export const TOPICS = TOPIC_CATEGORIES.flatMap((c, ci) =>
  c.questions.map((q) => ({ q, cat: ci })),
)

// prevCat(직전 질문의 카테고리)과 다른 카테고리에서 무작위로 하나를 뽑는다.
// prevCat < 0 이면 전체에서 뽑는다(최초 진입 시).
export function randomTopic(prevCat = -1) {
  const pool = prevCat < 0 ? TOPICS : TOPICS.filter((t) => t.cat !== prevCat)
  const list = pool.length ? pool : TOPICS
  return list[Math.floor(Math.random() * list.length)]
}
